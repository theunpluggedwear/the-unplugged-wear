export function pageTitleFor(pathname: string): string {
  const best = TITLES.filter(([prefix]) => pathname === prefix || pathname.startsWith(`${prefix}/`))
    .sort((a, b) => b[0].length - a[0].length)[0];
  return best?.[1] ?? 'Dashboard';
}
